-- 애플리케이션을 중지한 상태에서 SQLFLOW 또는 해당 테이블 DDL/DML 권한 계정으로 실행한다.
-- Oracle DDL은 자동 커밋된다. 과거 마이그레이션은 수정하지 않는다.
-- SELECT/DML은 유지하고 CREATE_VIEW와 CREATE_TABLE을 CREATE로 통합한다.
DECLARE
    INVALID_TYPE_COUNT NUMBER;
    CONSTRAINT_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO INVALID_TYPE_COUNT
    FROM SQLFLOW.QUERY_REQUEST
    WHERE REQUEST_TYPE IS NULL
       OR REQUEST_TYPE NOT IN ('SELECT', 'CREATE', 'CREATE_VIEW', 'CREATE_TABLE', 'INSERT', 'UPDATE', 'DELETE');

    IF INVALID_TYPE_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(-20012, '알 수 없는 요청 유형이 있습니다. 기존 데이터를 확인하세요.');
    END IF;

    -- 전환 중에도 요청 유형 제한을 유지한다. 재실행 시 기존 전환 제약을 사용한다.
    SELECT COUNT(*) INTO CONSTRAINT_COUNT
    FROM ALL_CONSTRAINTS
    WHERE OWNER = 'SQLFLOW' AND TABLE_NAME = 'QUERY_REQUEST'
      AND CONSTRAINT_NAME = 'CK_QUERY_REQUEST_TYPE_BRIDGE';

    IF CONSTRAINT_COUNT = 0 THEN
        EXECUTE IMMEDIATE q'[
            ALTER TABLE SQLFLOW.QUERY_REQUEST ADD CONSTRAINT CK_QUERY_REQUEST_TYPE_BRIDGE
            CHECK (REQUEST_TYPE IN ('SELECT', 'CREATE', 'CREATE_VIEW', 'CREATE_TABLE', 'INSERT', 'UPDATE', 'DELETE'))
        ]';
    END IF;

    -- 알려진 요청 유형 제약만 교체한다. 다른 제약조건은 변경하지 않는다.
    FOR C IN (
        SELECT CONSTRAINT_NAME FROM ALL_CONSTRAINTS
        WHERE OWNER = 'SQLFLOW' AND TABLE_NAME = 'QUERY_REQUEST'
          AND CONSTRAINT_NAME IN ('CK_QUERY_REQUEST_TYPE', 'CK_QUERY_REQUEST_TYPE_TYPE',
                                  'CK_QUERY_REQUEST_TYPE_V010', 'CK_QUERY_REQUEST_TYPE_V012')
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE SQLFLOW.QUERY_REQUEST DROP CONSTRAINT ' || C.CONSTRAINT_NAME;
    END LOOP;

    UPDATE SQLFLOW.QUERY_REQUEST SET REQUEST_TYPE = 'CREATE'
    WHERE REQUEST_TYPE IN ('CREATE_VIEW', 'CREATE_TABLE');
    COMMIT;

    EXECUTE IMMEDIATE q'[
        ALTER TABLE SQLFLOW.QUERY_REQUEST ADD CONSTRAINT CK_QUERY_REQUEST_TYPE_V012
        CHECK (REQUEST_TYPE IN ('SELECT', 'CREATE', 'INSERT', 'UPDATE', 'DELETE'))
    ]';
    EXECUTE IMMEDIATE 'ALTER TABLE SQLFLOW.QUERY_REQUEST DROP CONSTRAINT CK_QUERY_REQUEST_TYPE_BRIDGE';
END;
/

SELECT REQUEST_TYPE, COUNT(*) AS REQUEST_COUNT
FROM SQLFLOW.QUERY_REQUEST
GROUP BY REQUEST_TYPE;

SELECT CONSTRAINT_NAME, STATUS, SEARCH_CONDITION
FROM ALL_CONSTRAINTS
WHERE OWNER = 'SQLFLOW' AND TABLE_NAME = 'QUERY_REQUEST'
  AND CONSTRAINT_NAME = 'CK_QUERY_REQUEST_TYPE_V012';
