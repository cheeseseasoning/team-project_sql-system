CREATE TABLE VIEW_CREATE_RESULT (
    REQUEST_ID NUMBER(19) NOT NULL,
    RESULT_STATUS VARCHAR2(20) NOT NULL,
    RESULT_CONTENT CLOB NOT NULL,
    REGISTERED_BY NUMBER(19) NOT NULL,
    REGISTERED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_VIEW_CREATE_RESULT PRIMARY KEY (REQUEST_ID),
    CONSTRAINT FK_VIEW_CREATE_RESULT_REQUEST FOREIGN KEY (REQUEST_ID)
        REFERENCES QUERY_REQUEST (REQUEST_ID),
    CONSTRAINT FK_VIEW_CREATE_RESULT_USER FOREIGN KEY (REGISTERED_BY)
        REFERENCES USERS (USER_ID),
    CONSTRAINT CK_VIEW_CREATE_RESULT_STATUS
        CHECK (RESULT_STATUS IN ('COMPLETED', 'FAILED'))
);
