-- SQLFlow 관리 스키마의 QUERY_REQUEST 요청 유형 제약을 갱신한다.
-- SQLFLOW 사용자 또는 SQLFLOW.QUERY_REQUEST 변경 권한이 있는 계정(SYSTEM 등)으로 실행한다.
-- ALL_CONSTRAINTS를 사용하므로 현재 접속 사용자가 SQLFLOW가 아니어도 소유자 제약을 찾는다.
-- Oracle DDL은 자동 커밋된다. 허용되지 않는 기존 요청 유형이 있으면 변경 전에 중단한다.

DECLARE
    INVALID_TYPE_COUNT NUMBER;
    VERSIONED_CONSTRAINT_COUNT NUMBER;
    LEGACY_CONSTRAINT_COUNT NUMBER;
    CONSTRAINT_NAME_COLLISION NUMBER;
BEGIN
    -- 먼저 기존 데이터가 새 제약조건을 만족하는지 검사한다.
    SELECT COUNT(*) INTO INVALID_TYPE_COUNT
    FROM SQLFLOW.QUERY_REQUEST
    WHERE REQUEST_TYPE IS NULL
       OR REQUEST_TYPE NOT IN (
            'SELECT', 'CREATE_VIEW', 'CREATE_TABLE', 'INSERT', 'UPDATE', 'DELETE'
       );

    IF INVALID_TYPE_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20010,
            'QUERY_REQUEST에 새 요청 유형 목록에 없는 값이 있습니다. 데이터 확인 후 다시 실행하세요.'
        );
    END IF;

    -- 버전 제약 이름이 같은 스키마의 다른 테이블에서 사용 중이면 중단한다.
    SELECT COUNT(*) INTO CONSTRAINT_NAME_COLLISION
    FROM ALL_CONSTRAINTS
    WHERE OWNER = 'SQLFLOW'
      AND CONSTRAINT_NAME = 'CK_QUERY_REQUEST_TYPE_V010'
      AND TABLE_NAME <> 'QUERY_REQUEST';

    IF CONSTRAINT_NAME_COLLISION > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20011,
            'CK_QUERY_REQUEST_TYPE_V010 이름이 SQLFLOW의 다른 테이블에서 사용 중입니다.'
        );
    END IF;

    -- 이미 이 버전 제약이 있으면 유지해 재실행 시 제약을 불필요하게 제거하지 않는다.
    SELECT COUNT(*) INTO VERSIONED_CONSTRAINT_COUNT
    FROM ALL_CONSTRAINTS
    WHERE OWNER = 'SQLFLOW'
      AND TABLE_NAME = 'QUERY_REQUEST'
      AND CONSTRAINT_NAME = 'CK_QUERY_REQUEST_TYPE_V010';

    -- 새 제약 추가가 성공하기 전에는 기존 제약을 제거하지 않는다.
    IF VERSIONED_CONSTRAINT_COUNT = 0 THEN
        EXECUTE IMMEDIATE q'[
            ALTER TABLE SQLFLOW.QUERY_REQUEST ADD CONSTRAINT CK_QUERY_REQUEST_TYPE_V010
            CHECK (REQUEST_TYPE IN (
                'SELECT', 'CREATE_VIEW', 'CREATE_TABLE', 'INSERT', 'UPDATE', 'DELETE'
            ))
        ]';
    END IF;

    -- 이 테이블의 이전 요청 유형 제약만 제거한다. 다른 테이블은 건드리지 않는다.
    SELECT COUNT(*) INTO LEGACY_CONSTRAINT_COUNT
    FROM ALL_CONSTRAINTS
    WHERE OWNER = 'SQLFLOW'
      AND TABLE_NAME = 'QUERY_REQUEST'
      AND CONSTRAINT_NAME = 'CK_QUERY_REQUEST_TYPE';

    IF LEGACY_CONSTRAINT_COUNT > 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE SQLFLOW.QUERY_REQUEST DROP CONSTRAINT CK_QUERY_REQUEST_TYPE';
    END IF;

    SELECT COUNT(*) INTO LEGACY_CONSTRAINT_COUNT
    FROM ALL_CONSTRAINTS
    WHERE OWNER = 'SQLFLOW'
      AND TABLE_NAME = 'QUERY_REQUEST'
      AND CONSTRAINT_NAME = 'CK_QUERY_REQUEST_TYPE_TYPE';

    IF LEGACY_CONSTRAINT_COUNT > 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE SQLFLOW.QUERY_REQUEST DROP CONSTRAINT CK_QUERY_REQUEST_TYPE_TYPE';
    END IF;
END;
/

-- 적용 확인: 버전 제약에 CREATE_TABLE과 기존 요청 유형이 모두 허용되는지 확인한다.
SELECT OWNER, TABLE_NAME, CONSTRAINT_NAME, SEARCH_CONDITION
FROM ALL_CONSTRAINTS
WHERE OWNER = 'SQLFLOW'
  AND TABLE_NAME = 'QUERY_REQUEST'
  AND CONSTRAINT_NAME = 'CK_QUERY_REQUEST_TYPE_V010';
