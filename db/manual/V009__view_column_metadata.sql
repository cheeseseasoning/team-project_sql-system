-- SQLFlow 관리용 Oracle 계정에서 스크립트 전체를 실행한다.
-- 기존 환경의 수동 생성 테이블과 컬럼은 유지하고, 없는 항목만 추가한다.
-- 신규 환경에는 USERS, QUERY_REQUEST, DATA_RESOURCE가 먼저 준비되어 있어야 한다.
-- Oracle DDL은 자동 커밋된다. 실행 전 연결 계정과 대상 스키마를 확인한다.

DECLARE
    OBJECT_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO OBJECT_COUNT
    FROM USER_TABLES
    WHERE TABLE_NAME = 'VIEW_COLUMN_METADATA';

    IF OBJECT_COUNT = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE VIEW_COLUMN_METADATA (
                SCHEMA_NAME  VARCHAR2(128 CHAR) NOT NULL,
                OBJECT_NAME  VARCHAR2(128 CHAR) NOT NULL,
                COLUMN_NAME  VARCHAR2(128 CHAR) NOT NULL,
                LOGICAL_NAME VARCHAR2(255 CHAR),
                DESCRIPTION  VARCHAR2(1000 CHAR),
                UPDATED_BY   NUMBER,
                UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_VIEW_COLUMN_METADATA
                    PRIMARY KEY (SCHEMA_NAME, OBJECT_NAME, COLUMN_NAME)
            )';
    END IF;

    -- 이미 논리명 테이블을 사용 중인 환경에는 수정자 컬럼만 보완한다.
    SELECT COUNT(*) INTO OBJECT_COUNT
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'VIEW_COLUMN_METADATA' AND COLUMN_NAME = 'UPDATED_BY';

    IF OBJECT_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE VIEW_COLUMN_METADATA ADD (UPDATED_BY NUMBER)';
    END IF;

    SELECT COUNT(*) INTO OBJECT_COUNT
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'DATA_RESOURCE' AND COLUMN_NAME = 'CREATE_REQUEST_ID';

    IF OBJECT_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE DATA_RESOURCE ADD (CREATE_REQUEST_ID NUMBER(19))';
    END IF;

    -- 수동 적용 시 제약조건 이름이 달랐어도 같은 외래 키가 있으면 재생성하지 않는다.
    SELECT COUNT(*) INTO OBJECT_COUNT
    FROM USER_CONSTRAINTS C
    JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
    JOIN USER_CONSTRAINTS P ON P.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
    JOIN USER_CONS_COLUMNS PC
      ON PC.CONSTRAINT_NAME = P.CONSTRAINT_NAME AND PC.POSITION = CC.POSITION
    WHERE C.TABLE_NAME = 'VIEW_COLUMN_METADATA'
      AND C.CONSTRAINT_TYPE = 'R'
      AND CC.COLUMN_NAME = 'UPDATED_BY'
      AND P.TABLE_NAME = 'USERS'
      AND PC.COLUMN_NAME = 'USER_ID';

    IF OBJECT_COUNT = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE VIEW_COLUMN_METADATA
            ADD CONSTRAINT FK_VIEW_COL_METADATA_UPDATER
            FOREIGN KEY (UPDATED_BY) REFERENCES USERS (USER_ID)';
    END IF;

    SELECT COUNT(*) INTO OBJECT_COUNT
    FROM USER_CONSTRAINTS C
    JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
    JOIN USER_CONSTRAINTS P ON P.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
    JOIN USER_CONS_COLUMNS PC
      ON PC.CONSTRAINT_NAME = P.CONSTRAINT_NAME AND PC.POSITION = CC.POSITION
    WHERE C.TABLE_NAME = 'DATA_RESOURCE'
      AND C.CONSTRAINT_TYPE = 'R'
      AND CC.COLUMN_NAME = 'CREATE_REQUEST_ID'
      AND P.TABLE_NAME = 'QUERY_REQUEST'
      AND PC.COLUMN_NAME = 'REQUEST_ID';

    IF OBJECT_COUNT = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE DATA_RESOURCE
            ADD CONSTRAINT FK_DATA_RESOURCE_CREATE_REQ
            FOREIGN KEY (CREATE_REQUEST_ID) REFERENCES QUERY_REQUEST (REQUEST_ID)';
    END IF;
END;
/

COMMENT ON TABLE VIEW_COLUMN_METADATA IS '뷰 결과 컬럼의 논리명과 설명';
COMMENT ON COLUMN VIEW_COLUMN_METADATA.SCHEMA_NAME IS '업무 MySQL 스키마명';
COMMENT ON COLUMN VIEW_COLUMN_METADATA.OBJECT_NAME IS '실제 뷰 이름';
COMMENT ON COLUMN VIEW_COLUMN_METADATA.COLUMN_NAME IS '실제 뷰 결과 컬럼명';
COMMENT ON COLUMN VIEW_COLUMN_METADATA.LOGICAL_NAME IS '화면에 표시할 컬럼 논리명';
COMMENT ON COLUMN VIEW_COLUMN_METADATA.DESCRIPTION IS '뷰 결과 컬럼의 업무 의미와 설명';
COMMENT ON COLUMN VIEW_COLUMN_METADATA.UPDATED_BY IS '논리명 또는 설명을 마지막으로 저장한 사용자 ID';
COMMENT ON COLUMN VIEW_COLUMN_METADATA.UPDATED_AT IS '논리명 또는 설명의 최종 저장 시각';
COMMENT ON COLUMN DATA_RESOURCE.CREATE_REQUEST_ID IS '뷰를 처음 생성한 기안서 ID. NULL이면 연결된 생성 기안서 없음';

-- 적용 확인: 수정자, 수정 시각, 생성 기안서 연결 컬럼을 확인한다.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE
FROM USER_TAB_COLUMNS
WHERE (TABLE_NAME = 'VIEW_COLUMN_METADATA'
       AND COLUMN_NAME IN ('UPDATED_BY', 'UPDATED_AT'))
   OR (TABLE_NAME = 'DATA_RESOURCE' AND COLUMN_NAME = 'CREATE_REQUEST_ID')
ORDER BY TABLE_NAME, COLUMN_NAME;
