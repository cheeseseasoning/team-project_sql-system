-- 부서 일정 기능을 처음 적용하는 Oracle 환경에서 실행한다.
-- 이미 DEPARTMENT_SCHEDULE을 사용하는 환경은 기존 테이블을 유지한다.
DECLARE
    TABLE_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO TABLE_COUNT
    FROM USER_TABLES WHERE TABLE_NAME = 'DEPARTMENT_SCHEDULE';

    IF TABLE_COUNT = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE DEPARTMENT_SCHEDULE (
                SCHEDULE_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                DEPT_ID NUMBER(19) NOT NULL REFERENCES DEPARTMENT (DEPT_ID),
                CREATED_BY NUMBER(19) NOT NULL REFERENCES USERS (USER_ID),
                SCHEDULE_DATE DATE NOT NULL,
                TITLE VARCHAR2(100 CHAR) NOT NULL,
                MEMO VARCHAR2(500 CHAR)
            )';
        EXECUTE IMMEDIATE '
            CREATE INDEX IX_DEPT_SCHEDULE_DATE
            ON DEPARTMENT_SCHEDULE (DEPT_ID, SCHEDULE_DATE)';
    END IF;
END;
/
