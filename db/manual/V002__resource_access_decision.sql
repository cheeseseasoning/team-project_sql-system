-- 리소스 등록 및 부서 접근 정책 관리 지원
DECLARE
    v_count NUMBER;
    v_start NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'DATA_ACCESS_POLICY' AND COLUMN_NAME = 'ACCESS_DECISION';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE DATA_ACCESS_POLICY ADD (ACCESS_DECISION VARCHAR2(10) DEFAULT ''BLOCK'' NOT NULL)';
        -- 기존 활성 정책은 종전처럼 허용으로 보존한다.
        EXECUTE IMMEDIATE 'UPDATE DATA_ACCESS_POLICY SET ACCESS_DECISION = ''ALLOW'' WHERE ENABLED = ''Y''';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_DATA_RESOURCE';
    IF v_count = 0 THEN
        SELECT NVL(MAX(RESOURCE_ID), 0) + 1 INTO v_start FROM DATA_RESOURCE;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_DATA_RESOURCE START WITH ' || v_start || ' INCREMENT BY 1 NOCACHE';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_DATA_ACCESS_POLICY';
    IF v_count = 0 THEN
        SELECT NVL(MAX(POLICY_ID), 0) + 1 INTO v_start FROM DATA_ACCESS_POLICY;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_DATA_ACCESS_POLICY START WITH ' || v_start || ' INCREMENT BY 1 NOCACHE';
    END IF;
END;
/
