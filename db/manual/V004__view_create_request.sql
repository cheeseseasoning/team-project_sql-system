ALTER TABLE QUERY_REQUEST ADD REQUEST_TYPE VARCHAR2(20) DEFAULT 'SELECT' NOT NULL;

ALTER TABLE QUERY_REQUEST ADD CONSTRAINT CK_QUERY_REQUEST_TYPE
    CHECK (REQUEST_TYPE IN ('SELECT', 'CREATE_VIEW'));

CREATE SEQUENCE SEQ_VIEW_CREATE_SQL START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE VIEW_CREATE_SQL (
    QUERY_ID NUMBER(19) NOT NULL,
    REQUEST_ID NUMBER(19) NOT NULL,
    QUERY_ORDER NUMBER(2) NOT NULL,
    SQL_TITLE VARCHAR2(200),
    SQL_CONTENT CLOB NOT NULL,
    CREATE_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_VIEW_CREATE_SQL PRIMARY KEY (QUERY_ID),
    CONSTRAINT FK_VIEW_CREATE_SQL_REQUEST FOREIGN KEY (REQUEST_ID)
        REFERENCES QUERY_REQUEST (REQUEST_ID),
    CONSTRAINT UQ_VIEW_CREATE_SQL_ORDER UNIQUE (REQUEST_ID, QUERY_ORDER),
    CONSTRAINT CK_VIEW_CREATE_SQL_ORDER CHECK (QUERY_ORDER BETWEEN 1 AND 5)
);

CREATE INDEX IX_VIEW_CREATE_SQL_REQUEST
    ON VIEW_CREATE_SQL (REQUEST_ID, QUERY_ORDER);
