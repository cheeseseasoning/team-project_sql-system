-- 공지사항: 제목·본문과 작성/수정 정보를 저장한다.
CREATE TABLE NOTICE (
    NOTICE_ID  NUMBER(19)         NOT NULL,
    TITLE      VARCHAR2(200 CHAR) NOT NULL,
    CONTENT    CLOB              NOT NULL,
    CREATED_BY NUMBER(19)         NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY NUMBER(19),
    UPDATED_AT TIMESTAMP,

    CONSTRAINT PK_NOTICE PRIMARY KEY (NOTICE_ID),

    CONSTRAINT FK_NOTICE_CREATED_BY
        FOREIGN KEY (CREATED_BY) REFERENCES USERS (USER_ID),

    CONSTRAINT FK_NOTICE_UPDATED_BY
        FOREIGN KEY (UPDATED_BY) REFERENCES USERS (USER_ID),

    CONSTRAINT CK_NOTICE_TITLE
        CHECK (TRIM(TITLE) IS NOT NULL)
);

-- 공지 등록 시 SEQ_NOTICE.NEXTVAL로 고유 번호를 발급한다.
CREATE SEQUENCE SEQ_NOTICE
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

COMMENT ON TABLE NOTICE IS '공지사항';

COMMENT ON COLUMN NOTICE.NOTICE_ID IS '공지사항 고유 번호';
COMMENT ON COLUMN NOTICE.TITLE IS '공지 제목, 최대 200자';
COMMENT ON COLUMN NOTICE.CONTENT IS '공지 본문';
COMMENT ON COLUMN NOTICE.CREATED_BY IS '작성자 사용자 ID';
COMMENT ON COLUMN NOTICE.CREATED_AT IS '작성 시각';
COMMENT ON COLUMN NOTICE.UPDATED_BY IS '마지막 수정자 사용자 ID';
COMMENT ON COLUMN NOTICE.UPDATED_AT IS '마지막 수정 시각';