CREATE SEQUENCE SEQ_VIEW_CREATE_RESULT_HISTORY
    START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE VIEW_CREATE_RESULT_HISTORY (
    HISTORY_ID NUMBER(19) NOT NULL,
    REQUEST_ID NUMBER(19) NOT NULL,
    PREVIOUS_RESULT_STATUS VARCHAR2(20) NOT NULL,
    PREVIOUS_RESULT_CONTENT CLOB NOT NULL,
    PREVIOUS_REGISTERED_BY NUMBER(19) NOT NULL,
    PREVIOUS_REGISTERED_AT TIMESTAMP NOT NULL,
    CHANGED_BY NUMBER(19) NOT NULL,
    CHANGED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CHANGE_REASON VARCHAR2(1000) NOT NULL,
    CONSTRAINT PK_VIEW_CREATE_RESULT_HISTORY PRIMARY KEY (HISTORY_ID),
    CONSTRAINT FK_VCRH_REQUEST FOREIGN KEY (REQUEST_ID)
        REFERENCES QUERY_REQUEST (REQUEST_ID),
    CONSTRAINT FK_VCRH_PREV_USER FOREIGN KEY (PREVIOUS_REGISTERED_BY)
        REFERENCES USERS (USER_ID),
    CONSTRAINT FK_VCRH_CHANGED_USER FOREIGN KEY (CHANGED_BY)
        REFERENCES USERS (USER_ID),
    CONSTRAINT CK_VCRH_RESULT_STATUS
        CHECK (PREVIOUS_RESULT_STATUS IN ('COMPLETED', 'FAILED'))
);

CREATE INDEX IX_VCRH_REQUEST_TIME
    ON VIEW_CREATE_RESULT_HISTORY (REQUEST_ID, CHANGED_AT, HISTORY_ID);
